WITH MAJ_ECO AS(
SELECT COUNTRY, SUM(VALUE) AS TOTAL_GDP FROM GDP_3 GROUP BY COUNTRY ORDER BY TOTAL_GDP DESC LIMIT 2
),
TOT_CON AS(
SELECT COUNTRY, YEAR, SUM(CONSUMPTION) AS TOTAL_CONSUMPTION
FROM CONSUMPTION group by COUNTRY, YEAR),
CT AS(
SELECT COUNTRY, YEAR, TOTAL_CONSUMPTION,
LAG(TOTAL_CONSUMPTION) OVER (PARTITION BY COUNTRY ORDER BY YEAR) AS PREV_CONS
FROM TOT_CON
)
SELECT CT.COUNTRY, CT.YEAR, CT.TOTAL_CONSUMPTION,
CT.TOTAL_CONSUMPTION - CT.PREV_CONS AS CONSUMPTION_CHANGE ,
CASE 
WHEN PREV_CONS IS NULL THEN "First Year"
WHEN TOTAL_CONSUMPTION > PREV_CONS THEN "Increased"
WHEN TOTAL_CONSUMPTION < PREV_CONS THEN "Decreased"
ELSE "No change"
END AS CON_TREND
FROM CT WHERE CT.COUNTRY IN (SELECT COUNTRY FROM MAJ_ECO)
ORDER BY COUNTRY, YEAR;

