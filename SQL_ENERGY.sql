-- 16) Which countries have improved (reduced) their per capita emissions the most over the last decade?
WITH PER_CAP AS (
    SELECT 
        E.COUNTRY,
        E.YEAR,
        E.EMISSION / P.VALUE AS PER_CAPITA_EMISSION,
        FIRST_VALUE(E.EMISSION / P.VALUE) 
            OVER (PARTITION BY E.COUNTRY ORDER BY E.YEAR) AS FIRST_YEAR_PCE,
        LAST_VALUE(E.EMISSION / P.VALUE) 
            OVER (PARTITION BY E.COUNTRY ORDER BY E.YEAR 
                  ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS LAST_YEAR_PCE
    FROM EMISSION_TOTAL E JOIN POPULATION P	ON E.COUNTRY = P.COUNTRIES
	AND E.YEAR = P.YEAR
)
SELECT 
    COUNTRY, 
    FIRST_YEAR_PCE AS START_PCE,
    LAST_YEAR_PCE AS END_PCE,
    (FIRST_YEAR_PCE - LAST_YEAR_PCE) AS IMPROVED_BY
FROM PER_CAP
GROUP BY COUNTRY, FIRST_YEAR_PCE, LAST_YEAR_PCE
ORDER BY IMPROVED_BY DESC LIMIT 10;


