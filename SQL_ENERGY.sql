	   SUM(C.CONSUMPTION) AS TOTAL_CONSUMPTION,
       SUM(P.PRODUCTION) - SUM(C.CONSUMPTION) AS NET_COMPARISON, 
	   CASE
			WHEN SUM(P.PRODUCTION) > SUM(C.CONSUMPTION) THEN "SURPLUS"
            WHEN SUM(P.PRODUCTION) < SUM(C.CONSUMPTION) THEN "DEFICIT"
