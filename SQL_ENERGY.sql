-- What is the correlation between GDP growth and energy production growth?

WITH TOT_PRO AS(
SELECT COUNTRY, YEAR, SUM(PRODUCTION) AS TOTAL_PRODUCTION FROM PRODUCTION GROUP BY COUNTRY, YEAR
),
TREND AS(
SELECT P.COUNTRY, P.YEAR, G.VALUE AS GDP, P.TOTAL_PRODUCTION AS PRODUCTION ,
G.VALUE - LAG(G.VALUE) OVER (PARTITION BY COUNTRY ORDER BY YEAR) AS GDP_CHANGE,
P.TOTAL_PRODUCTION - LAG(P.TOTAL_PRODUCTION) OVER (PARTITION BY COUNTRY ORDER BY YEAR) AS PROD_CHANGE
FROM TOT_PRO P 
JOIN GDP_3 G ON
P.COUNTRY = G.COUNTRY AND
P.YEAR = G.YEAR
ORDER BY COUNTRY, YEAR
)
SELECT *,
CASE 
WHEN GDP_CHANGE IS NULL THEN "STARTING YEAR"
WHEN GDP_CHANGE < 0 THEN "GDP Decreased"
WHEN GDP_CHANGE > 0 THEN "GDP Increased"
ELSE "NO CHANGE"
END AS GDP_TREND,
CASE
WHEN PROD_CHANGE IS NULL THEN "STARTING YEAR"
WHEN PROD_CHANGE < 0 THEN "PROD Decreased"
WHEN PROD_CHANGE > 0 THEN "PROD Increased"
ELSE "NO CHANGE"
END AS PROD_TREND
FROM TREND;


