-- 7) How has population growth affected total emissions in each country?

WITH EMISSION_POP_TREND AS(
SELECT E.COUNTRY, E.YEAR, E.EMISSION, P.VALUE AS POPULATION, 
(E.EMISSION - LAG(E.EMISSION) OVER (PARTITION BY E.COUNTRY ORDER BY E.YEAR)) AS EMI_CHANGE,
(P.VALUE - LAG(P.VALUE) OVER (PARTITION BY P.COUNTRIES ORDER BY P.YEAR)) AS POP_CHANGE
FROM EMISSION_TOTAL E
JOIN POPULATION P 
ON E.COUNTRY = P.COUNTRIES AND
E.YEAR = P.YEAR)
SELECT COUNTRY, YEAR, EMISSION, POPULATION, EMI_CHANGE,POP_CHANGE,
CASE 
WHEN EMI_CHANGE IS NULL THEN "START_YEAR"
WHEN EMI_CHANGE > 0 THEN "Emission increased"
WHEN EMI_CHANGE < 0 THEN "Emission decreased"
ELSE "NO CHANGE"
END AS EMISSION_TREND,
CASE 
WHEN POP_CHANGE IS NULL THEN "START_YEAR"
WHEN POP_CHANGE > 0 THEN "Population increased"
WHEN POP_CHANGE < 0 THEN "Population decreased"
ELSE "NO CHANGE"
END AS POPULATION_TREND
FROM EMISSION_POP_TREND
ORDER BY COUNTRY, YEAR;




